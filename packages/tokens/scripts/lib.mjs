// Pure helpers for turning src/tokens.json into CSS variables and typed values.
// No dependencies on purpose: the token pipeline should be easy to read end to end.

import { readFileSync } from 'node:fs';

export const PREFIX = 'maru';

const REF = /^\{([^{}]+)\}$/;

export function loadTokens() {
  return JSON.parse(readFileSync(new URL('../src/tokens.json', import.meta.url), 'utf8'));
}

/** Flatten a token group into `{ path, value }` leaves. */
export function flatten(node, path = []) {
  return Object.entries(node).flatMap(([key, value]) =>
    typeof value === 'string' ? [{ path: [...path, key], value }] : flatten(value, [...path, key]),
  );
}

export function isRef(value) {
  return REF.test(value);
}

export function refPath(value) {
  const match = REF.exec(value);
  if (!match) throw new Error(`Not a token reference: ${value}`);
  return match[1].split('.');
}

function lookup(root, path) {
  let node = root;
  for (const key of path) {
    if (node === null || typeof node !== 'object' || !(key in node)) {
      throw new Error(`Unresolved token reference: {${path.join('.')}}`);
    }
    node = node[key];
  }
  if (typeof node !== 'string') {
    throw new Error(`Token reference points to a group, not a value: {${path.join('.')}}`);
  }
  return node;
}

/** Follow `{palette.gray.900}` style references until a raw value is reached. */
export function resolveValue(root, value, trail = []) {
  if (!isRef(value)) return value;
  const path = refPath(value);
  const id = path.join('.');
  if (trail.includes(id)) {
    throw new Error(`Circular token reference: ${[...trail, id].join(' -> ')}`);
  }
  return resolveValue(root, lookup(root, path), [...trail, id]);
}

/**
 * Token path -> CSS custom property name.
 *   palette.gray.900            -> --maru-palette-gray-900
 *   scale.space.4               -> --maru-space-4
 *   semantic.light.color.bg.default -> --maru-color-bg-default
 */
export function cssVarName(path) {
  const [group, ...rest] = path;
  let segments;
  if (group === 'palette') segments = path;
  else if (group === 'scale') segments = rest;
  else if (group === 'semantic')
    segments = rest.slice(1); // drop shared | light | dark
  else throw new Error(`Unknown token group: ${group}`);
  return `--${PREFIX}-${segments.join('-')}`;
}

/**
 * Collect CSS variables per output block. Semantic tokens keep their alias
 * chain (`var(--maru-palette-blue-600)`) so it is visible in DevTools.
 */
export function collectVariables(root) {
  const toVariable = ({ path, value }) => {
    resolveValue(root, value); // fail early on broken or circular references
    return {
      name: cssVarName(path),
      value: isRef(value) ? `var(${cssVarName(refPath(value))})` : value,
    };
  };

  return {
    base: [
      ...flatten(root.palette, ['palette']),
      ...flatten(root.scale, ['scale']),
      ...flatten(root.semantic.shared, ['semantic', 'shared']),
    ].map(toVariable),
    light: flatten(root.semantic.light, ['semantic', 'light']).map(toVariable),
    dark: flatten(root.semantic.dark, ['semantic', 'dark']).map(toVariable),
  };
}

export function buildCss(root) {
  const { base, light, dark } = collectVariables(root);
  const declarations = (variables, indent) =>
    variables.map(({ name, value }) => `${indent}${name}: ${value};`).join('\n');

  return (
    [
      '/* Generated by scripts/build.mjs from src/tokens.json. Do not edit. */',
      `:root {\n${declarations(base, '  ')}\n}`,
      `:root,\n[data-theme='light'] {\n  color-scheme: light;\n${declarations(light, '  ')}\n}`,
      `[data-theme='dark'] {\n  color-scheme: dark;\n${declarations(dark, '  ')}\n}`,
      // Follow the OS setting unless the page explicitly opts into light.
      `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n    color-scheme: dark;\n${declarations(dark, '    ')}\n  }\n}`,
    ].join('\n\n') + '\n'
  );
}

function resolveTree(root, node) {
  return Object.fromEntries(
    Object.entries(node).map(([key, value]) => [
      key,
      typeof value === 'string' ? resolveValue(root, value) : resolveTree(root, value),
    ]),
  );
}

/** Same shape as tokens.json, with every reference replaced by its raw value. */
export function buildResolved(root) {
  return {
    palette: resolveTree(root, root.palette),
    scale: resolveTree(root, root.scale),
    semantic: {
      shared: resolveTree(root, root.semantic.shared),
      light: resolveTree(root, root.semantic.light),
      dark: resolveTree(root, root.semantic.dark),
    },
  };
}

export function buildJs(resolved) {
  return (
    '// Generated by scripts/build.mjs. Do not edit.\n' +
    `export const tokens = ${JSON.stringify(resolved, null, 2)};\n\n` +
    "export const themes = ['light', 'dark'];\n"
  );
}

export function buildDts(resolved) {
  return (
    '// Generated by scripts/build.mjs. Do not edit.\n' +
    `export declare const tokens: ${JSON.stringify(resolved, null, 2)};\n\n` +
    "export declare const themes: readonly ['light', 'dark'];\n"
  );
}

// ---- WCAG contrast -------------------------------------------------------

function channel(value) {
  const s = value / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex) {
  const match = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!match) throw new Error(`Expected #rrggbb color, got: ${hex}`);
  const n = parseInt(match[1], 16);
  return (
    0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255)
  );
}

export function contrastRatio(a, b) {
  const [lighter, darker] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (lighter + 0.05) / (darker + 0.05);
}
